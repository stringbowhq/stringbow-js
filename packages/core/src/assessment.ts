// What a decision says: the claims an assessment makes about the evidence, and the decision vocabulary.
// Both SDKs and the API share these shapes. How a policy turns an assessment into a decision is in policy.ts.

export type ClaimStatus = 'holds' | 'uncertain' | 'fails' | 'no_evidence';
export type ClaimName = 'same_operator' | 'human_input' | 'steady_session';
export type Decision = 'allow' | 'challenge' | 'hold' | 'deny';
/**
 * How a challenge may be completed. `passkey` is a Stringbow passkey that signs the request hash. `customer` is a
 * step-up the customer runs themselves and reports from their backend with a server key. `sandbox_confirm` is sandbox only.
 */
export type ChallengeMethod = 'passkey' | 'customer' | 'sandbox_confirm';
export const CHALLENGE_METHODS: ChallengeMethod[] = ['passkey', 'customer', 'sandbox_confirm'];
/** What the customer says their own step-up was. Recorded on the challenge and in the audit log; not verified by Stringbow. */
export const CUSTOMER_CHALLENGE_KINDS = ['passkey', 'totp', 'push', 'sms_otp', 'email_otp', 'password', 'other'] as const;
export type CustomerChallengeKind = (typeof CUSTOMER_CHALLENGE_KINDS)[number];

/**
 * One typed claim. Every claim is phrased so that "holds" is the good state:
 *  - same_operator:  the person who enrolled is the one producing this input
 *  - human_input:    the input was made by hand, not generated by a script or agent
 *  - steady_session: the person at the controls has not changed since earlier in this session
 */
export interface Claim {
  status: ClaimStatus;
  /** Probability the claim holds, when the model can state one. Null otherwise. */
  confidence: number | null;
  /** True only when `confidence` comes from a calibration fit on held-out people. */
  calibrated: boolean;
  /** How much usable evidence backs the claim, 0..1. */
  coverage: number;
  /** Age of the newest evidence used, ms. Null when there is none. */
  freshness_ms: number | null;
  /** Which model layers contributed. */
  basis: string[];
  /** Machine-readable detail: rule codes, missing-evidence notes. */
  notes: string[];
}

export interface Assessment {
  at: number;
  claims: Record<ClaimName, Claim>;
  evidence: {
    windows: number; keys: number; strokes: number; clicks: number; active_ms: number; coverage_keys: number; coverage_pointer: number;
    /** Finger gestures (swipes, taps, on-screen key presses), field-focus changes and windows with device motion. */
    touches: number; focus_changes: number; motion_windows: number; coverage_touch: number;
    /**
     * How the latest text entry before the decision was made (see lastTextEntry). `without_keys` means the text in
     * this action was not typed: claims scored on typing describe earlier input, not this text. Absent in
     * assessments made before it was added.
     */
    text_entry?: 'typed' | 'pasted' | 'without_keys' | 'on_screen_keyboard' | 'none';
    /** Insertions without a key press behind them in that entry. */
    text_without_keys?: number;
  };
  subject: { state: string; baseline: boolean };
  model: { rules: string; personal: string; encoder: string | null; pointer_encoder?: string | null; provenance: string; sources?: string };
  limits: string[];
}
